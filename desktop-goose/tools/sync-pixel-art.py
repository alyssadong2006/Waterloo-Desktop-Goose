#!/usr/bin/env python3
"""Generate or verify the Windows sprite table from the canonical Swift art."""
from argparse import ArgumentParser
from pathlib import Path
import re
import sys

root = Path(__file__).resolve().parents[1]
output = root / "windows" / "PixelArt.cs"
source = (root / "pixel_art.swift").read_text() + "\n" + (root / "coyote_art.swift").read_text()
pattern = re.compile(r"    static let (\w+) = Sprite\(rows: \[\n(.*?)\n    \]\)", re.S)
sprites = []
for name, body in pattern.findall(source):
    rows = re.findall(r'^\s*"([A-Z.]+)"', body, re.M)
    if rows:
        sprites.append((name, rows))

palette = {
    "K": (64, 59, 84), "W": (255, 252, 245), "E": (43, 38, 59), "H": (255, 255, 255),
    "R": (255, 92, 122), "B": (255, 255, 252), "F": (250, 140, 92), "C": (255, 212, 163),
    "A": (230, 51, 56), "N": (28, 28, 36), "T": (122, 99, 74), "U": (222, 209, 184),
    "V": (89, 71, 51), "Y": (255, 204, 38), "M": (199, 23, 46), "P": (255, 140, 158),
    "G": (245, 224, 128), "L": (186, 171, 92), "Z": (166, 115, 250), "I": (235, 224, 255),
    "S": (217, 222, 240), "O": (255, 189, 66), "D": (227, 133, 36),
    "Q": (140, 120, 99), "X": (97, 79, 69), "J": (10, 46, 82),
}

names = [name for name, _ in sprites]
if len(names) != len(set(names)):
    raise SystemExit("duplicate canonical sprite names")
for name, rows in sprites:
    if len({len(row) for row in rows}) != 1:
        raise SystemExit(f"{name} has inconsistent row widths")
    unknown = set("".join(rows)) - set(palette) - {"."}
    if unknown:
        raise SystemExit(f"{name} uses colors missing from the Windows palette: {sorted(unknown)}")

lines = ["// Generated by tools/sync-pixel-art.py from the canonical Swift art. Do not hand-edit.",
         "namespace DesktopGoose;", "", "internal static class PixelArt", "{",
         "    internal static readonly Dictionary<char, Color> Palette = new()", "    {"]
for key, rgb in palette.items():
    lines.append(f"        ['{key}'] = Color.FromArgb({rgb[0]}, {rgb[1]}, {rgb[2]}),")
lines += ["    };", "", "    internal static readonly Dictionary<string, string[]> Sprites = new()", "    {"]
for name, rows in sprites:
    lines.append(f'        ["{name}"] =')
    lines.append("        [")
    lines.extend(f'            "{row}",' for row in rows)
    lines.append("        ],")
lines += ["    };", "}", ""]
generated = "\n".join(lines)

parser = ArgumentParser()
parser.add_argument("--check", action="store_true", help="fail instead of rewriting a stale generated file")
args = parser.parse_args()

if args.check:
    if not output.exists() or output.read_text() != generated:
        print("windows/PixelArt.cs is stale; run python tools/sync-pixel-art.py", file=sys.stderr)
        raise SystemExit(1)
    print(f"Verified {len(sprites)} Windows sprites and the shared palette")
else:
    output.write_text(generated)
    print(f"Synced {len(sprites)} sprites to windows/PixelArt.cs")
